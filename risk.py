"""
Оцінка репутаційного ризику 0-10 за формулою чотирьох факторів.

    Risk = F1*0.35 + F2*0.25 + F3*0.25 + F4*0.15

    F1  Вірусність та охоплення    35%
    F2  Критичність теми           25%
    F3  Загроза бізнесу / чурн     25%
    F4  Тональність та докази      15%

Шкала інтерпретації:
    0.0-2.9  низький      стандартна відповідь за скриптом
    3.0-5.9  середній     відповідь SMM протягом 1-2 годин
    6.0-7.9  високий      ескалація на PR-менеджера
    8.0-10   критичний    антикризовий штаб, офіційна позиція

ЩО МИ РЕАЛЬНО МІРЯЄМО, А ЩО НІ — читати перед тим, як називати цифру журі.

F1. Повна версія фактора вимагає авторитету автора й кількості його
    підписників. Для окремої людини це персональні дані, які ми свідомо
    не збираємо (кейс забороняє прямо). Тому F1 рахується з того, що
    є відкритою метрикою ВИДАННЯ, а не людини: тип джерела й реальна
    кількість підписників каналу (channel_sizes.json, зібрано з
    публічних сторінок t.me). Для відгуків у магазинах застосунків
    охоплення вважається низьким — там немає ні поширень, ні стрічки.
    Це заниження, і його треба назвати вголос.

F4. Наявність скріншота, відео чи аудіо ми бачимо тільки якщо автор
    згадує їх текстом. Вкладення з Google Play і App Store не приходять.
    Тобто F4 систематично занижений на відгуках.

F2 і F3 рахуються за змістом тексту й вимірюються повноцінно.
"""

import json
import os
import re

# ------------------------------------------------------------------ F1

CHANNEL_SIZES = {}
if os.path.exists('channel_sizes.json'):
    with open('channel_sizes.json', encoding='utf-8') as f:
        CHANNEL_SIZES = {k: v for k, v in json.load(f).items() if v}


def f1_reach(source_type, source_name):
    """Охоплення. Реальні розміри каналів, не здогадки."""
    if source_type == 'review':
        # Відгук у магазині: без стрічки, без поширень, без підписників.
        return 2.0

    if source_type == 'news':
        # Публікація в ЗМІ. За шкалою це 9-10, але ми не розрізняємо
        # велике видання від агрегатора, тому беремо нижню межу.
        return 8.0

    if source_type == 'telegram':
        subs = CHANNEL_SIZES.get(source_name)
        if not subs:
            return 4.0
        if subs >= 1_000_000:
            return 10.0
        if subs >= 300_000:
            return 8.5
        if subs >= 50_000:
            return 7.0
        if subs >= 5_000:
            return 5.0
        return 3.0

    return 3.0


# ------------------------------------------------------------------ F2

# 9-10: витік даних, загроза життю, шахрайство топменеджменту, ворог
F2_EXTREME = re.compile(
    r'витік\w*\s+(даних|персональн)|злив\w*\s+(баз|даних)|персональн\w*\s+дан\w*\s+'
    r'(витек|злит|продан)|зв\W?язку?\s+під\s+час\s+(тривог|обстріл|повітрян)|'
    r'не\s+працю\w*\s+під\s+час\s+(тривог|обстріл)|'
    # неможливість викликати екстрені служби — найважчий випадок:
    # це вже не про зручність, а про загрозу життю
    r'не\s+(міг|мог|можу|можн)\w*\s+(ви|до)?клика\w*\s+(швидк|101|102|103|рятув)|'
    r'(не\s+працю\w*|нема\w*|зник\w*|відсутн\w*).{0,40}під\s+час\s+(повітрян\w*\s+)?(тривог|обстріл)|'
    r'під\s+час\s+(повітрян\w*\s+)?тривог\w*.{0,40}(не\s+працю|нема|відсутн|зник)|'
    r'співпрац\w*\s+з\s+(ворог|рф|росі)|фінансу\w*\s+ворог|шахрайств\w*\s+керівн',
    re.IGNORECASE)

# 6-8: системний обман, приховані платежі, масовий збій, кібератака
F2_HIGH = re.compile(
    r'масов\w*\s+(збій|відключ|скарг)|системн\w*\s+(обман|проблем)|'
    r'прихован\w*\s+(платеж|комісі|умов)|кібератак|зламал\w*\s+систем|'
    r'обман\w*\s+(клієнт|абонент)|'
    # "по всій Україні" саме по собі нічого не означає: так пишуть і про
    # запуск нової послуги. Потрібне слово про поломку поряд.
    r'по\s+всій\s+(країні|україні).{0,40}(не\s+працю|збій|нема|відсутн|проблем)|'
    r'(не\s+працю\w*|збій|нема\w*|відсутн\w*).{0,40}по\s+всій\s+(країні|україні)|'
    r'вся\s+(область|країна)\s+без',
    re.IGNORECASE)

# 3-5: тарифи, помилкове списання, затримка підтримки
F2_MEDIUM = re.compile(
    r'списа\w*\s+(кошт|гро|баланс)|зня\w*\s+гро|підвищ\w*\s+(тариф|цін)|'
    r'подорожч|не\s+можу\s+дозвонит\w*\s+в\s+підтримк|'
    r'підтримка\s+не\s+відповіда|чека\w*\s+\d+\s+(хвилин|годин|днів)',
    re.IGNORECASE)


def f2_severity(text, cause):
    if F2_EXTREME.search(text):
        return 9.5
    if F2_HIGH.search(text):
        return 7.0
    if cause == 'outage':
        return 7.0
    if F2_MEDIUM.search(text):
        return 4.0
    if cause in ('coverage', 'internet', 'calls'):
        return 3.0
    return 1.5


# ------------------------------------------------------------------ F3

# 9-10: бойкот, організована атака, суд, розірвання контрактів
F3_EXTREME = re.compile(
    r'бойкот|масово\s+(перех|йдемо|відмов)|подаю\s+до\s+суду|судов\w*\s+позов|'
    r'колективн\w*\s+(позов|скарг)|розрива\w*\s+(контракт|договор|договір)|'
    r'закликаю\s+всіх|давайте\s+всі\s+(перей|відмов)',
    re.IGNORECASE)

# 6-8: заклики до MNP, скарги в держоргани
# Конкуренти — потрібні, щоб відрізнити заклик піти від власної реклами
# оператора про перенесення номера ДО нього.
_RIVAL = r'(київстар|kyivstar|lifecell|лайфсел|інш\w*\s+оператор)'

F3_HIGH = re.compile(
    # MNP і "переходьте" лише поряд із конкурентом. Інакше під це
    # підпадала власна реклама Vodafone, а "Переходьте до" ловилось
    # у пості про правила переходу дороги.
    rf'\bmnp\b.{{0,60}}{_RIVAL}|{_RIVAL}.{{0,60}}\bmnp\b|'
    rf'перенес\w*\s+номер.{{0,60}}{_RIVAL}|'
    rf'переходьте\s+(до|на)\s+{_RIVAL}|'
    rf'радж\w*\s+(змінит|перейт).{{0,40}}{_RIVAL}|'
    r'скаржт\w*\s+(в|до)\s+(нкек|нкрзі|держ)|скарг\w*\s+в\s+(нкек|нкрзі)|'
    r'пишіть\s+скарг|всім\s+радж\w*\s+(піти|змінит)',
    re.IGNORECASE)

# 3-5: особистий намір піти
F3_MEDIUM = re.compile(
    r'(піду|перейду|зміню|відмовл\w*)\s+(до|на|від)?\s*(київстар|lifecell|лайф|'
    r'інш\w*\s+оператор)|якщо\s+не\s+(полаг|виправ|вирішит).{0,30}(піду|перейду)|'
    r'прощава\w*\s+vodafone|більше\s+не\s+буду\s+(користув|платит)',
    re.IGNORECASE)


def f3_threat(text):
    if F3_EXTREME.search(text):
        return 9.5
    if F3_HIGH.search(text):
        return 7.0
    if F3_MEDIUM.search(text):
        return 4.0
    return 1.0


# ------------------------------------------------------------------ F4

# 9-10: запис розмови, юридична претензія
F4_EXTREME = re.compile(
    r'запис\w*\s+(розмов|дзвінк)|аудіозапис|відеозапис|'
    r'юридичн\w*\s+претензі|офіційн\w*\s+претензі|нотаріальн',
    re.IGNORECASE)

# 6-8: скріншот, speedtest, листування
F4_HIGH = re.compile(
    r'скрін|скриншот|screenshot|speedtest|спідтест|заміри\s+швидкост|'
    r'фото\s+(чек|рахунк|екран)|листуванн\w*\s+з\s+підтримк|'
    r'додаю\s+(фото|скрін|докази)|ось\s+(скрін|фото|докази)',
    re.IGNORECASE)


def f4_evidence(text, q):
    """
    Докази й переконливість.

    q — ознаки з quality.score(): дата, технічні деталі, опис звернення.
    Емоційний крик без фактів опускає оцінку до нуля.
    """
    if F4_EXTREME.search(text):
        return 9.5
    if F4_HIGH.search(text):
        return 7.0

    details = sum([q['has_date'], q['has_tech_detail'],
                   q['has_process_detail'], q['has_micro_location']])
    if details >= 2:
        return 5.0
    if details == 1:
        return 3.5
    if q['emotional_noise'] >= 0.6:
        return 0.5
    return 1.5


# ------------------------------------------------------------------ реклама

# Власні промо-пости операторів. Вони потрапляють у збір разом із новинами,
# і без цього фільтра реклама тарифу в мільйонному каналі опиняється
# нагорі списку репутаційних ризиків — лише за охоплення.
AD_RX = re.compile(
    r'підключа(й|йте|ти)\b|замов(ляй|те)\b|акці\w*\s+від|знижк\w*\s+\d+\s*%|'
    r'тариф\w*\s+[«"]|детал\w*\s+за\s+посиланн|переходь\s+за\s+посиланн|'
    r'вигідн\w*\s+тариф|спеціальн\w*\s+пропозиці|дізнатись\s+більше\s+за',
    re.IGNORECASE)


def is_advertising(text):
    return bool(AD_RX.search(text))


# ------------------------------------------------------------------ підсумок

WEIGHTS = {'f1': 0.35, 'f2': 0.25, 'f3': 0.25, 'f4': 0.15}

GRADES = [
    (8.0, 'critical', 'Негайне сповіщення PR-директора та антикризового штабу. '
                      'Потрібна офіційна позиція компанії.'),
    (6.0, 'high', 'Пріоритетна обробка, ескалація на PR-менеджера '
                  'або керівника підтримки.'),
    (3.0, 'medium', 'Відповідь SMM протягом 1-2 годин, переведення спілкування '
                    'в приватні повідомлення.'),
    (0.0, 'low', 'Стандартна відповідь за скриптом у загальному порядку.'),
]


def grade(score):
    for threshold, name, action in GRADES:
        if score >= threshold:
            return name, action
    return 'low', GRADES[-1][2]


def compute(text, sentiment_name, source_type, source_name, cause, q):
    """
    Повертає {score, grade, action, factors}.

    Позитивна згадка ризику не створює — 0 без розрахунку.
    """
    text = text or ''

    # Нейтральне повідомлення репутаційного ризику не створює.
    # Без цих воріт формула дає рекламі тарифів у мільйонному каналі
    # 3.5 бала лише за охоплення — і реклама опиняється нагорі списку
    # ризиків. Ваги факторів при цьому лишаються недоторканими.
    if is_advertising(text) or sentiment_name not in ('negative', 'mixed'):
        return {'score': 0.0, 'grade': 'low', 'action': GRADES[-1][2],
                'factors': {'f1': 0, 'f2': 0, 'f3': 0, 'f4': 0}}

    f = {
        'f1': f1_reach(source_type, source_name),
        'f2': f2_severity(text, cause),
        'f3': f3_threat(text),
        'f4': f4_evidence(text, q),
    }
    # Другі ворота: охоплення саме по собі не є ризиком. Якщо в тексті
    # немає ні серйозної теми (F2), ні загрози чи закликів (F3), то це
    # просто популярний пост, а не репутаційна подія.
    if f['f2'] < 3.0 and f['f3'] < 3.0:
        return {'score': 0.0, 'grade': 'low', 'action': GRADES[-1][2], 'factors': f}

    score = sum(f[k] * WEIGHTS[k] for k in f)

    # Змішана тональність — скарга всередині загалом позитивного тексту.
    # Ризик реальний, але нижчий за чистий негатив.
    if sentiment_name == 'mixed':
        score *= 0.7

    score = round(min(score, 10.0), 2)
    name, action = grade(score)
    return {'score': score, 'grade': name, 'action': action, 'factors': f}


