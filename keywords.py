"""
Словники пошуку. Учасник №2.

Два незалежні фільтри:

1. БРЕНД — пост називає оператора. Дає порівняння конкурентів.
2. ПОКРИТТЯ — пост описує проблему зі звʼязком, навіть без назви оператора.
   "їду в потязі, звʼязку немає" бренд не згадує, але це рівно той сигнал,
   заради якого будується система.

Пост зберігається, якщо спрацював ХОЧА Б ОДИН фільтр.

Апостроф в українській пишуть по-різному: звʼязок, зв'язок, зв'язок, звязок.
Скрізь використовується APO замість одного символу, інакше половина
скарг не знайдеться.
"""

import re

# Будь-який апостроф або його відсутність.
APO = r"['’ʼ`´]?"

# ------------------------------------------------------------------ бренди

BRAND_PATTERNS = {
    'vodafone': [
        r'vodafone\w*',
        r'водафон\w*',
        r'водофон\w*',          # часта помилка в написанні
    ],
    'kyivstar': [
        r'kyivstar\w*',
        r'київстар\w*',
        r'киевстар\w*',
    ],
    'lifecell': [
        r'lifecell\w*',
        r'life\s?cell\w*',
        r'лайфсел\w*',
        r'лайфцел\w*',
    ],
}

# Шумні варіанти, вмикаються прапорцем --loose.
LOOSE_PATTERNS = {
    'vodafone': [r'\bвф\b', r'\bvf\b'],
    'lifecell': [r'\bлайф\b'],
}

# ------------------------------------------------------------------ покриття

# Проблема зі звʼязком. Українською і російською — у телеграмі пишуть обома.
COVERAGE_PATTERNS = [
    # немає сигналу
    rf'не\s+лови(ть|т)\b',
    rf'нема(є)?\s+зв{APO}?язку',
    rf'зв{APO}?язку?\s+нема(є)?\b',          # зворотний порядок слів
    rf'без\s+зв{APO}?язку',
    rf'зв{APO}?язок\s+(зник|пропав|відсутн|впав)',
    rf'відсутн\w*\s+зв{APO}?язок',
    r'нет\s+связи',
    r'связи\s+нет\b',
    r'связь\s+(пропал|исчезл|отсутств)',
    r'no\s+signal',

    # мережа і сигнал
    r'нема(є)?\s+мереж',
    r'мереж[іа]\s+нема(є)?\b',
    r'нет\s+сети',
    r'нема(є)?\s+сигнал',
    r'нет\s+сигнала',
    r'слабк\w*\s+сигнал',
    r'слабый\s+сигнал',

    # інтернет
    r'не\s+працює\s+(мобільний\s+)?інтернет',
    r'інтернет\s+не\s+працює',
    r'не\s+работает\s+интернет',
    r'интернет\s+не\s+работает',
    r'нема(є)?\s+інтернет',
    r'інтернет[уа]?\s+нема(є)?\b',
    r'нет\s+интернета',
    r'інтернет\s+(ледве|ели)\s+',
    r'не\s+тягне\s+інтернет',

    # покриття як тема
    r'покритт\w*',
    r'покрыти\w*',
    r'мобільн\w*\s+зв{APO}?язок',

    # технології — слабкий сигнал сам по собі, але в парі з проблемою корисний
    r'\b[345]g\b',
    r'\blte\b',
]

# ------------------------------------------------------------------ контекст

# Навіщо: журі питає "що саме сталося". Контекст відповідає на це
# ще до LLM і дає №5 змогу не плутати аварію з хронічною прогалиною.
CONTEXT_PATTERNS = {
    # дорога: хронічна прогалина вздовж маршруту, не аварія
    'transport': [
        r'потяг\w*', r'поїзд\w*', r'потязі', r'поезд\w*', r'электричк\w*',
        r'електричк\w*', r'укрзалізни\w*', r'укрзализны\w*',
        r'\bтрас\w*', r'шосе', r'автобус\w*', r'маршрутк\w*',
        r'в\s+дорозі', r'в\s+дороге',
    ],
    # рельєф: структурне обмеження покриття
    'terrain': [
        r'гор(ах|и|ам)\b', r'карпат\w*', r'полонин\w*',
        r'\bліс(і|у)\b', r'\bв\s+сел(і|е)\b', r'передгір\w*',
    ],
    # світло: НЕ провина оператора, базові станції на акумуляторах
    'blackout': [
        r'світл[оа]', r'\bсвет\b', r'відключенн\w*', r'отключени\w*',
        r'блекаут', r'блэкаут', r'знеструмл\w*', r'обесточ\w*',
        r'\bдтек\b', r'укренерго', r'генератор\w*', r'графік\w*\s+відключ',
    ],
    # приміщення: точкова проблема, не масова
    'indoor': [
        r'\bметро\b', r'підвал\w*', r'укритт\w*', r'\bтрц\b',
        r'\bліфт\w*', r'паркінг\w*', r'бомбосховищ\w*',
    ],
}


def _compile(patterns):
    joined = '|'.join(f'(?:{p})' for p in patterns)
    return re.compile(joined, re.IGNORECASE | re.UNICODE)


def build_brand_matchers(loose=False):
    matchers = {}
    for brand, patterns in BRAND_PATTERNS.items():
        all_patterns = list(patterns)
        if loose:
            all_patterns += LOOSE_PATTERNS.get(brand, [])
        matchers[brand] = _compile(all_patterns)
    return matchers


COVERAGE_RX = _compile(COVERAGE_PATTERNS)
CONTEXT_RX = {name: _compile(pats) for name, pats in CONTEXT_PATTERNS.items()}


def detect_brands(text, matchers):
    """Які оператори названі в тексті. Порожньо — жодного."""
    return [brand for brand, rx in matchers.items() if rx.search(text)]


def is_coverage_issue(text):
    """Чи пост описує проблему зі звʼязком або покриттям."""
    return bool(COVERAGE_RX.search(text))


def detect_context(text):
    """Обставини проблеми: дорога, гори, світло, приміщення."""
    return [name for name, rx in CONTEXT_RX.items() if rx.search(text)]
