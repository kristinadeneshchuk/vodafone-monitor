def is_coverage_issue(text):
    """Чи пост описує проблему зі звʼязком або покриттям."""
    return bool(COVERAGE_RX.search(text))


def detect_context(text):
    """Обставини проблеми: дорога, гори, світло, приміщення."""
    return [name for name, rx in CONTEXT_RX.items() if rx.search(text)]


