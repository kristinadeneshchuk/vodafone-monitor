CAUSE_RX = [(name, _compile(pats)) for name, pats in CAUSE_PATTERNS]


def detect_cause(text):
    """
    Причина скарги з фіксованого списку. Перша збіжність зверху вниз.

    Порядок навмисний: 'blackout' перевіряється першим, бо скарга
    "через відключення світла немає інтернету" — це не збій оператора,
    і плутати її з 'internet' не можна, інакше детектор підніматиме
    тривогу на кожному віяловому відключенні.
    """
    for name, rx in CAUSE_RX:
        if rx.search(text):
            return name
    return 'other'
