export async function POST(req: NextRequest) {
  try {
    const { message, history = [] } = await req.json();

    if (!message || typeof message !== 'string') {
      return NextResponse.json({ error: 'Повідомлення обов’язкове' }, { status: 400 });
    }

    const rawKey = process.env.GEMINI_API_KEY || process.env.NEXT_PUBLIC_GEMINI_API_KEY;
    const apiKey = rawKey ? rawKey.trim().replace(/^["']|["']$/g, '') : '';
    const isValidKey = apiKey && apiKey !== 'your_gemini_api_key_here' && apiKey.length > 10;

    if (isValidKey) {
      try {
        const ai = new GoogleGenAI({ apiKey });

        // Build conversation contents
        const contents: Array<{ role: 'user' | 'model'; parts: Array<{ text: string }> }> = [];

        // Context injection
        contents.push({
          role: 'user',
          parts: [{
            text: `${SYSTEM_INSTRUCTION}\n\nОсь повна інформація та вибірка даних за рік для використання у відповідях:\n${TELECOM_DATASET_CONTEXT}\n\nКористувач ставить тобі питання. Відповідай строго за інструкцією.`
          }]
        });
        contents.push({
          role: 'model',
          parts: [{
            text: 'Зрозумів. Інструкцію прийнято. Готовий надавати чітку аналітику, прогнози та рекомендації ПА ДЄЛУ без зайвих слів на основі 1 051 звернення та телеметрії Vodafone за 2025–2026 роки.'
          }]
        });

        // Previous conversation turns
        if (Array.isArray(history)) {
          history.slice(-6).forEach(h => {
            if (h.role && h.content) {
              contents.push({
                role: h.role === 'user' ? 'user' : 'model',
                parts: [{ text: h.content }]
              });
            }
          });
        }

        // Current message
        contents.push({
          role: 'user',
          parts: [{ text: message }]
        });

        const response = await ai.models.generateContent({
          model: 'gemini-3.6-flash',
          contents: contents as any,
        });

        const reply = response.text?.trim();
        if (reply) {
          return NextResponse.json({ reply, source: 'gemini-3.6-flash' });
        }
      } catch (geminiError) {
        console.error('[Analytics Chat] Gemini API error, using smart fallback engine:', geminiError);
      }
    }

    // Heuristic predictive fallback engine
    const reply = generateHeuristicPredictionReply(message);
    return NextResponse.json({ reply, source: 'analytical-engine' });

  } catch (error: any) {
    console.error('[Analytics Chat] Internal error:', error);
    return NextResponse.json({ error: 'Помилка обробки запиту' }, { status: 500 });
  }
}

