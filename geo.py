# Маршрут: "траса Київ-Чоп", "потяг Київ - Харків", "дорога Одеса—Львів".
ROUTE_RX = re.compile(
    r'(?:трас\w*|дорог\w*|шосе|потяг\w*|поїзд\w*|поезд\w*|маршрут\w*)\s*'
    r'[«"]?([А-ЯІЇЄA-Z][а-яіїєґa-z\'\-]{2,20})\s*[-–—]\s*'
    r'([А-ЯІЇЄA-Z][а-яіїєґa-z\'\-]{2,20})',
    re.UNICODE)

# Кінцеві пункти трас, яких немає серед обласних центрів.
EXTRA_POINTS = {
    'Чоп': (48.4333, 22.2000),
    'Ягодин': (51.2400, 23.7200),
    'Краковець': (49.9600, 23.1700),
}


def _point(name):
    """Координати за назвою пункту: місто, зона або відомий пункт траси."""
    if name in CITY_COORDS:
        return CITY_COORDS[name]
    if name in AREAS:
        return AREAS[name]
    return EXTRA_POINTS.get(name)


def _normalize_endpoint(raw):
    """Приводить кінцевий пункт траси до назви зі словника."""
    stem = raw.lower()[:5]
    for city in CITY_COORDS:
        if city.lower().startswith(stem) or stem.startswith(city.lower()[:5]):
            return city
    for point in EXTRA_POINTS:
        if point.lower().startswith(stem):
            return point
    return None


def resolve(text, source_type=None):
    """
    Локація повідомлення або None.

    Повертає {'lat', 'lng', 'addressName', 'kind', 'precision'}.
    precision: district | city | area | route — №6 може малювати
    точку або відрізок різного розміру залежно від точності.
    """
    t = strip_chrome(text, source_type)

    # 1. Маршрут — перевіряємо першим: у "потяг Київ-Харків" є два міста,
    # і без цієї перевірки ми б записали скаргу в Київ, а вона про дорогу.
    m = ROUTE_RX.search(t)
    if m:
        # Підпис за типом маршруту: потяг це не траса, і на карті №6
        # різниця видна користувачу.
        kind_word = 'Маршрут' if re.search(
            r'потяг|поїзд|поезд', m.group(0), re.IGNORECASE) else 'Траса'
        a = _normalize_endpoint(m.group(1))
        b = _normalize_endpoint(m.group(2))
        pa, pb = _point(a) if a else None, _point(b) if b else None
        if pa and pb:
            return {
                'lat': round((pa[0] + pb[0]) / 2, 4),
                'lng': round((pa[1] + pb[1]) / 2, 4),
                'addressName': f'{kind_word} {a}–{b}',
                'kind': 'route',
                'precision': 'route',
            }

    cities = detect_cities(t, source_type)

    # 2. Район міста — найточніше, що в нас є.
    if len(cities) == 1:
        city = cities[0]
        for (c, district), coords in DISTRICTS.items():
            if c == city and re.search(district.lower()[:6], t, re.IGNORECASE):
                return {
                    'lat': coords[0], 'lng': coords[1],
                    'addressName': f'{city}, {district}',
                    'kind': 'district', 'precision': 'district',
                }

    # 3. Природна зона.
    for area, rx in AREA_RX.items():
        if rx.search(t):
            lat, lng = AREAS[area]
            return {'lat': lat, 'lng': lng, 'addressName': area,
                    'kind': 'area', 'precision': 'area'}

    # 4. Місто. Два міста в тексті — локація неоднозначна, краще None.
    if len(cities) == 1 and cities[0] in CITY_COORDS:
        lat, lng = CITY_COORDS[cities[0]]
        return {'lat': lat, 'lng': lng, 'addressName': cities[0],
                'kind': 'city', 'precision': 'city'}

    # 5. Область: "на Львівщині", "у Закарпатті". Точка — обласний
    # центр, але точність нижча, і підпис це показує. Перевіряється
    # ПІСЛЯ міста: у "Львівщина, Дрогобич" точніша саме друга частина.
    oblasts = detect_oblasts(t, source_type)
    if len(oblasts) == 1 and oblasts[0] in OBLAST_COORDS:
        lat, lng = OBLAST_COORDS[oblasts[0]]
        return {'lat': lat, 'lng': lng, 'addressName': oblasts[0],
                'kind': 'oblast', 'precision': 'oblast'}

    return None


