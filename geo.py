"""
Геокодування без зовнішнього API. Роль №4, контракт для №6.

Віддає {lat, lng, addressName} або None.

Три рівні точності, від найточнішого:
  1. місто + район   -> координати району, якщо він відомий
  2. місто           -> координати центру міста
  3. траса / маршрут -> середина відрізка між двома містами

Свідомо НЕ вгадуємо. Якщо локації в тексті немає — None. Вигадана
локація гірша за відсутню: вона створює фантомний кластер на карті,
і команда поїде розбиратись туди, де нічого не сталось.
"""

